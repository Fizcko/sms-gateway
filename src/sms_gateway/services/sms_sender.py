"""Hand outgoing SMS to gammu-smsd, through the outbox tables."""

from threading import Lock
from typing import Any, Protocol


class SmsSender(Protocol):
    def send(self, number: str, message: str) -> str:
        """Queue a message for a number and return its outbox ID."""
        ...


class GammuSmsSender:
    """Sends through python-gammu.

    The gammu import and the SMSD handle wait for the first send: creating the
    handle reads the configuration generated by the entrypoint. The lock is there
    because the library gives no thread-safety guarantee and routes run in a pool.
    """

    def __init__(self, config_path: str) -> None:
        self._config_path = config_path
        self._lock = Lock()
        self._smsd: Any = None

    def send(self, number: str, message: str) -> str:
        import gammu
        import gammu.smsd

        encoded = gammu.EncodeSMS(
            {
                "Class": -1,
                "Unicode": True,
                "Entries": [{"ID": "ConcatenatedTextLong", "Buffer": message}],
            }
        )
        for sms in encoded:
            sms["SMSC"] = {"Location": 1}
            sms["Number"] = number
        with self._lock:
            if self._smsd is None:
                self._smsd = gammu.smsd.SMSD(self._config_path)
            return str(self._smsd.InjectSMS(encoded))
